        "    \n",
        "    canonical_prompt = train_samples[0][0][\"value\"]\n",
        "    eos_id = tok.convert_tokens_to_ids(\"<|END_OF_TURN_TOKEN|>\")\n",
        "    pad_id = tok.pad_token_id or tok.eos_token_id\n",
        "    model.eval()\n",
        "    \n",
        "    for idx, t in enumerate(tasks):\n",
        "        engine.reset()\n",
        "        q = t[\"user_query\"]\n",
        "        expected_ans = t[\"oracle_answer\"]\n",
        "        \n",
        "        prompt = (\n",
        "            f\"<|START_OF_TURN_TOKEN|><|SYSTEM_TOKEN|>{canonical_prompt}<|END_OF_TURN_TOKEN|>\"\n",
        "            f\"<|START_OF_TURN_TOKEN|><|USER_TOKEN|>{q}<|END_OF_TURN_TOKEN|>\"\n",
        "        )\n",
        "        \n",
        "        turns = []\n",
        "        has_tool_action = False\n",
        "        all_schemas_valid = True\n",
        "        final_answer = None\n",
        "        \n",
        "        for turn_idx in range(max_turns):\n",
        "            active_prompt = prompt + \"<|START_OF_TURN_TOKEN|><|CHATBOT_TOKEN|>\"\n",
        "            enc = tok(active_prompt, return_tensors=\"pt\").to(device)\n",
        "            \n",
