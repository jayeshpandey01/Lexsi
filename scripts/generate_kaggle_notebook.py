            "                \n",
            "                if role in (\"system\",):\n",
            "                    formatted = f\"<|START_OF_TURN_TOKEN|><|SYSTEM_TOKEN|>{val}<|END_OF_TURN_TOKEN|>\"\n",
            "                    tokens = self.tokenizer.encode(formatted, add_special_tokens=False)\n",
            "                    full_tokens.extend(tokens)\n",
            "                    loss_mask.extend([False] * len(tokens))\n",
            "                elif role in (\"human\", \"user\"):\n",
            "                    formatted = f\"<|START_OF_TURN_TOKEN|><|USER_TOKEN|>{val}<|END_OF_TURN_TOKEN|>\"\n",
            "                    tokens = self.tokenizer.encode(formatted, add_special_tokens=False)\n",
            "                    full_tokens.extend(tokens)\n",
            "                    loss_mask.extend([False] * len(tokens))\n",
            "                elif role in (\"gpt\", \"assistant\"):\n",
            "                    prefix = \"<|START_OF_TURN_TOKEN|><|CHATBOT_TOKEN|>\"\n",
            "                    suffix = \"<|END_OF_TURN_TOKEN|>\"\n",
            "                    p_tok = self.tokenizer.encode(prefix, add_special_tokens=False)\n",
            "                    val_tok = self.tokenizer.encode(val, add_special_tokens=False)\n",
            "                    s_tok = self.tokenizer.encode(suffix, add_special_tokens=False)\n",
            "                    \n",
            "                    full_tokens.extend(p_tok + val_tok + s_tok)\n",
            "                    loss_mask.extend([False] * len(p_tok)) # Mask prefix\n",
            "                    loss_mask.extend([True] * len(val_tok))  # Active loss\n",
            "                    loss_mask.extend([True] * len(s_tok))   # Supervise turn end\n",
            "                elif role in (\"observation\", \"tool\"):\n",
            "                    formatted = f\"<|START_OF_TURN_TOKEN|><|SYSTEM_TOKEN|>Observation: {val}<|END_OF_TURN_TOKEN|>\"\n",
