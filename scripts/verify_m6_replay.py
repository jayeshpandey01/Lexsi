"""Milestone 6 Offline Replay Verification Script.

Replays historical validation outputs generated by sft_aya_3b_v2_c3 (Milestone 5)
through the enhanced runtime parser and executes extracted actions against the
sandboxed database engine to verify empirical tool execution fidelity.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List

from src.environment.sandbox import SandboxedToolEngine, ToolObservation
from src.runtime.parser import parse_agent_output


def run_m6_replay() -> Dict[str, Any]:
    trace_path = Path("results/runs/sft_aya_3b_v2_c3/val_rollout_traces.json")
    if not trace_path.exists():
        raise FileNotFoundError(f"Trace file not found at {trace_path}")

    with open(trace_path, "r", encoding="utf-8") as f:
        traces = json.load(f)

    engine = SandboxedToolEngine(seed=42, use_database=True)
    engine.reset()

    replayed_results: List[Dict[str, Any]] = []
    extracted_tools_count = 0
    executed_tools_count = 0
    clean_observations_count = 0

    print("=" * 80)
    print("MILESTONE 6: OFFLINE VALIDATION TRACE REPLAY & TOOL EXECUTION VERIFICATION")
    print(f"Loaded {len(traces)} historical traces from {trace_path}")
    print("=" * 80)

    for idx, trace in enumerate(traces):
        task_id = trace["task_id"]
        user_query = trace["user_query"]
        raw_output = trace["turns"][0]["model_output"]

        # Parse with enhanced M6 parser
        thought, action, final_answer, parse_error = parse_agent_output(raw_output)

        extracted = action is not None
        if extracted:
            extracted_tools_count += 1

        obs_data: Dict[str, Any] = {}
        if extracted and action is not None:
            # Execute in sandboxed tool engine
            obs: ToolObservation = engine.execute(action.tool_name, action.arguments)
            executed_tools_count += 1
            if not obs.is_error:
                clean_observations_count += 1
                obs_data = {
                    "is_error": False,
                    "record_count": len(obs.result) if isinstance(obs.result, list) else 1,
                    "sample": obs.result[:2] if isinstance(obs.result, list) else obs.result,
                }
            else:
                obs_data = {
                    "is_error": True,
                    "error_code": obs.error_code,
                    "error_message": obs.error_message,
                }

        replayed_results.append({
            "task_id": task_id,
            "has_tool_action_original": trace.get("has_tool_action", False),
            "has_tool_action_m6": extracted,
            "action": action.model_dump() if action else None,
            "parse_error": parse_error,
            "observation_summary": obs_data,
        })

        print(f"\n[Trace {idx:02d}] {task_id}")
        print(f"  Query: {user_query[:75]}...")
        if extracted and action:
            print(f"  M6 Extracted Tool: {action.tool_name}({action.arguments})")
            if not obs_data.get("is_error"):
                print(f"  Execution: SUCCESS -> Retrieved {obs_data.get('record_count')} records from database")
            else:
                print(f"  Execution: ERROR -> {obs_data.get('error_code')}: {obs_data.get('error_message')}")
        else:
            print(f"  M6 Extracted Tool: None (Parse Error: {parse_error})")

    summary = {
        "total_traces": len(traces),
        "m5_tool_calling_rate": sum(1 for t in traces if t.get("has_tool_action", False)) / len(traces),
        "m6_replayed_tool_calling_rate": extracted_tools_count / len(traces),
        "execution_success_rate": clean_observations_count / len(traces),
        "traces": replayed_results,
    }

    print("\n" + "=" * 80)
    print("REPLAY SUMMARY RESULTS:")
    print(f"  Original M5 Tool-Calling Rate (M2): {summary['m5_tool_calling_rate'] * 100:.1f}% (0/{len(traces)})")
    print(f"  M6 Replayed Tool-Calling Rate (M2): {summary['m6_replayed_tool_calling_rate'] * 100:.1f}% ({extracted_tools_count}/{len(traces)})")
    print(f"  Database Execution Success Rate:    {summary['execution_success_rate'] * 100:.1f}% ({clean_observations_count}/{len(traces)})")
    print("=" * 80)

    out_file = Path("results/m6_offline_replay_summary.json")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)
    print(f"Wrote summary to {out_file}")

    return summary


if __name__ == "__main__":
    run_m6_replay()
